//! Headless layout contract for the reusable UI building blocks added for the
//! debug surface (`ui/components/*` plus the new `Metro` token groups)
//! and for the debug screen's left control column assembled from them.
//!
//! The building blocks are Slint components, so their layout contract cannot
//! be asserted by source inspection: `build.rs` compiles the test-only
//! showcase (`tests/components_showcase.slint`) out of the real component
//! files, this test instantiates it with the Slint testing backend (no display
//! server, software renderer) and measures the resulting element tree — the
//! same headless pattern `src/icon_geometry.rs` uses for the icon size
//! contract.
//!
//! It lives in `tests/` (a separate test binary) on purpose: Slint installs
//! exactly one platform per process and the binary already claims the testing
//! backend in `icon_geometry`, so a unit-test module would collide with it.
//!
//! The assertions are geometric because Slint 1.18.1 emits layout debug info
//! (`ElementHandle::layout_kind`) only for a component's box layouts, not for
//! the `GridLayout`/`FlexboxLayout` at a component root — a root `GridLayout`
//! reports no layout kind. The measured columns and the flex wrap prove the
//! layouts just as directly.
//!
//! It also carries a `FlexboxLayout` check: a wrapping flex box must compile
//! and lay out under the software renderer. (It is already in production use
//! as `CatalogGrid`, so this guards the contract rather than probing an
//! unknown feature.)
//!
//! The second window is the debug screen itself: the regrouped left control
//! column must keep its card groups, its stepper raster and — because
//! the desktop pilot suite is not part of the fast gate — the accessible
//! names that suite addresses by label.

#![allow(clippy::expect_used, clippy::unwrap_used)]

use std::sync::Once;

use i_slint_backend_testing::{AccessibleRole, ElementHandle, ElementQuery, ElementRoot};
use slint::{ComponentHandle, Model};

/// The showcase window and its `FlexWrapBox` case, generated by `build.rs` from
/// `tests/components_showcase.slint`.
#[rustfmt::skip]
#[allow(unused_qualifications, clippy::unwrap_used, clippy::expect_used)]
mod showcase {
    include!(concat!(env!("OUT_DIR"), "/components_showcase.rs"));
}

/// The 15 colour tokens `theme.slint` exported before the token groups were
/// added; the shipping screens still consume them.
const LEGACY_TOKEN_COUNT: usize = 15;

/// Sub-pixel layout rounding tolerance, in logical pixels.
const TOLERANCE: f32 = 1.0;

/// Installs the testing backend once per process (a Slint platform can only be
/// installed once). `renderer-software` gives the headless window a rasterizer.
fn install_testing_backend() {
    static INSTALL: Once = Once::new();
    INSTALL.call_once(|| {
        slint::platform::set_platform(Box::new(i_slint_backend_testing::TestingBackend::new(
            i_slint_backend_testing::TestingBackendOptions {
                mock_time: true,
                threading: false,
                renderer_name: Some("software".into()),
            },
        )))
        .expect("the component contract needs the testing backend");
    });
}

fn shown_showcase() -> showcase::ComponentsShowcase {
    install_testing_backend();
    let app = showcase::ComponentsShowcase::new().expect("ComponentsShowcase::new failed");
    app.show().expect("ComponentsShowcase::show failed");
    english();
    app
}

/// The debug-screen showcase on the same testing backend and thread.
fn shown_debug_showcase() -> showcase::DebugScreenShowcase {
    install_testing_backend();
    let app = showcase::DebugScreenShowcase::new().expect("DebugScreenShowcase::new failed");
    app.show().expect("DebugScreenShowcase::show failed");
    english();
    app
}

/// The contract names controls by their English accessible labels, but a window
/// picks its language from the desktop locale when it is created.
fn english() {
    slint::select_bundled_translation("en-US").expect("en-US is bundled");
}

fn find(root: &impl ElementRoot, type_name: &str) -> ElementHandle {
    ElementQuery::from_root(root)
        .match_type_name(type_name)
        .find_first()
        .unwrap_or_else(|| panic!("{type_name} not found in the showcase window"))
}

/// All instances of one named element inside `root` (a repeated element shares
/// its id across the instances).
fn by_id(root: &ElementHandle, id: &str) -> Vec<ElementHandle> {
    let handles: Vec<ElementHandle> = root.query_descendants().match_id(id).find_all();
    assert!(
        !handles.is_empty(),
        "no element id {id} in the showcase window"
    );
    handles
}

/// The x positions of the given elements, in order, with duplicates collapsed.
fn columns(handles: &[ElementHandle]) -> Vec<i64> {
    let mut xs: Vec<i64> = handles
        .iter()
        .map(|handle| handle.absolute_position().x.round() as i64)
        .collect();
    xs.sort_unstable();
    xs.dedup();
    xs
}

fn same_width(handles: &[ElementHandle]) -> bool {
    let first = handles[0].size().width;
    handles
        .iter()
        .all(|handle| (handle.size().width - first).abs() <= TOLERANCE)
}

/// One test body: the testing backend binds its platform to the thread that
/// installed it, so every window measurement runs here.
#[test]
fn building_blocks_hold_their_layout_contract() {
    let app = shown_showcase();

    // ── The legacy colour token surface must survive ───────────────────
    assert_eq!(
        app.get_legacy_tokens().row_count(),
        LEGACY_TOKEN_COUNT,
        "theme.slint must keep exporting the legacy colour tokens the shipping screens consume"
    );

    // ── Every building block is present and laid out ───────────────────
    for type_name in [
        "Card",
        "SectionTitle",
        "KeyValueGrid",
        "StatusBadge",
        "IconButton",
        "LabeledStepper",
        "FlexWrapBox",
    ] {
        let handle = find(&app, type_name);
        let size = handle.size();
        assert!(
            size.width > 0.0 && size.height > 0.0,
            "{type_name} must be laid out with a positive size, saw {}x{}",
            size.width,
            size.height
        );
    }
    assert_eq!(
        ElementQuery::from_root(&app)
            .match_type_name("StatusBadge")
            .find_all()
            .len(),
        4,
        "the showcase must render one badge per status kind"
    );

    // ── KeyValueGrid: fixed label column, constrained value column ─────
    let grid = find(&app, "KeyValueGrid");
    let grid_position = grid.absolute_position();
    let grid_size = grid.size();
    let labels = by_id(&grid, "KeyValueGrid::key-label");
    let values = by_id(&grid, "KeyValueGrid::key-value");
    assert_eq!(labels.len(), 3, "one label per key/value row");
    assert_eq!(values.len(), 3, "one value per key/value row");
    let label_columns = columns(&labels);
    let value_columns = columns(&values);
    assert_eq!(label_columns.len(), 1, "labels share one column");
    assert_eq!(value_columns.len(), 1, "values share one column");
    assert!(
        value_columns[0] > label_columns[0],
        "the value column must start after the label column"
    );
    assert!(
        same_width(&labels),
        "the label column must be a fixed width"
    );
    // One of the values is long enough to need eliding: if the value cell grew
    // with its text instead of eliding, this width would differ from the rest.
    assert!(
        same_width(&values),
        "the value column must constrain the cell, not grow with the text"
    );
    for cell in labels.iter().chain(values.iter()) {
        let position = cell.absolute_position();
        let size = cell.size();
        assert!(
            size.width > 0.0,
            "every key/value cell must have a width, saw {size:?}"
        );
        assert!(
            position.x + size.width <= grid_position.x + grid_size.width + TOLERANCE,
            "a key/value cell must stay inside the grid"
        );
    }

    // ── LabeledStepper: the raster columns line up across rows ─────────
    let steppers = ElementQuery::from_root(&app)
        .match_type_name("LabeledStepper")
        .find_all();
    assert_eq!(
        steppers.len(),
        2,
        "the showcase must render two stepper rows"
    );
    let mut row_columns = Vec::new();
    for stepper in &steppers {
        let label = by_id(stepper, "LabeledStepper::step-label");
        let unit = by_id(stepper, "LabeledStepper::unit-text");
        let hint = by_id(stepper, "LabeledStepper::hint-text");
        let spin_box = stepper
            .query_descendants()
            .match_type_name("NumericSpinBox")
            .find_first()
            .expect("a LabeledStepper row must carry the shared NumericSpinBox");
        let mut cells: Vec<ElementHandle> = label.clone();
        cells.push(spin_box);
        cells.extend(unit.iter().cloned());
        cells.extend(hint.iter().cloned());
        assert_eq!(cells.len(), 4, "one label, stepper, unit and hint per row");
        row_columns.push(columns(&cells));
    }
    assert_eq!(
        row_columns[0], row_columns[1],
        "the stepper raster columns must line up across rows"
    );
    assert_eq!(
        row_columns[0].len(),
        4,
        "a row must have four distinct layout columns"
    );

    // ── FlexboxLayout wrap case: compiles, lays out and wraps ──────────────
    let flex = find(&app, "FlexWrapBox");
    let cells: Vec<ElementHandle> = flex
        .query_descendants()
        .match_type_name("Rectangle")
        .find_all()
        .into_iter()
        .filter(|cell| {
            let size = cell.size();
            (size.width - 100.0).abs() <= TOLERANCE && (size.height - 40.0).abs() <= TOLERANCE
        })
        .collect();
    assert_eq!(
        cells.len(),
        3,
        "the flex box must expose its three fixed cells"
    );
    let mut rows: Vec<i64> = cells
        .iter()
        .map(|cell| cell.absolute_position().y.round() as i64)
        .collect();
    rows.sort_unstable();
    rows.dedup();
    assert_eq!(
        rows.len(),
        2,
        "three 100px cells in a 220px box must wrap onto two rows, saw rows at {rows:?}"
    );

    // ── The debug screen's left control column ─────────────────────────
    debug_control_column_holds_its_contract(&shown_debug_showcase());

    // ── The debug screen's right panes with seeded content ─────────────
    debug_panels_hold_their_contract(&shown_debug_panel_showcase());
}

/// The debug-screen showcase with one seeded live OCR panel.
fn shown_debug_panel_showcase() -> showcase::DebugPanelShowcase {
    install_testing_backend();
    let app = showcase::DebugPanelShowcase::new().expect("DebugPanelShowcase::new failed");
    app.show().expect("DebugPanelShowcase::show failed");
    app
}

/// The right-pane contract of the debug screen: a seeded live OCR
/// panel renders inside a card and carries its source line and its
/// rows. The live/stored provenance is a contract, so it is asserted through
/// the accessible names the projection sets, not by pixel probing.
fn debug_panels_hold_their_contract(app: &showcase::DebugPanelShowcase) {
    // The seeded OCR panel renders inside a card (the left column's scroll
    // view intersects a different number of cards per viewport, so the count
    // is not pinned here — the panel's own content is).
    assert!(
        ElementQuery::from_root(app)
            .match_type_name("Card")
            .find_first()
            .is_some(),
        "the seeded OCR panel must render inside a card"
    );
    assert!(
        has_label(app, "Live, generation 3."),
        "the OCR panel must carry its provenance line"
    );
    assert!(
        has_label(app, "0 +10 Strength"),
        "the OCR panel must render its live row"
    );
}

/// The regrouped left control column of the debug screen: five
/// named group cards, the seventeen-row stepper raster on pinned columns, and
/// the accessible names the desktop pilot matrix addresses.
///
/// The raster assertions are geometric on purpose. `LabeledStepper` pins the
/// label, stepper and unit columns, so what has to hold is that every row sits
/// on the same columns and that the cells stay inside their row — a column
/// that outgrew the control column overflows exactly there, which is the first
/// failure a font, token or caption change produces.
fn debug_control_column_holds_its_contract(app: &showcase::DebugScreenShowcase) {
    // ── The five group headings ────────────────────────────────────────
    assert_eq!(
        ElementQuery::from_root(app)
            .match_type_name("Card")
            .find_all()
            .len(),
        5,
        "the control column must group its controls into five cards"
    );
    for heading in [
        "Display",
        "Actions",
        "Tooltip & areas",
        "Crash logs",
        "Artifacts",
    ] {
        assert!(
            has_label(app, heading),
            "the {heading:?} card must render its group heading"
        );
    }

    // ── The stepper raster ─────────────────────────────────────────────
    let rows = ElementQuery::from_root(app)
        .match_type_name("LabeledStepper")
        .find_all();
    assert_eq!(
        rows.len(),
        17,
        "the tooltip & areas card must carry one stepper row per numeric setting"
    );
    let mut raster_columns: Option<Vec<i64>> = None;
    for row in &rows {
        let row_position = row.absolute_position();
        let row_size = row.size();
        let mut cells: Vec<ElementHandle> = by_id(row, "LabeledStepper::step-label");
        cells.extend(by_id(row, "LabeledStepper::unit-text"));
        cells.extend(
            row.query_descendants()
                .match_type_name("NumericSpinBox")
                .find_all(),
        );
        assert_eq!(
            cells.len(),
            3,
            "a raster row must carry its label, its stepper and its unit"
        );
        for cell in &cells {
            let position = cell.absolute_position();
            let size = cell.size();
            assert!(
                position.x >= row_position.x - TOLERANCE
                    && position.x + size.width <= row_position.x + row_size.width + TOLERANCE,
                "a raster cell must stay inside its row: cell {}..{} in row {}..{}",
                position.x,
                position.x + size.width,
                row_position.x,
                row_position.x + row_size.width
            );
        }
        let columns = columns(&cells);
        assert_eq!(columns.len(), 3, "a row must have three distinct columns");
        match &raster_columns {
            Some(expected) => assert_eq!(
                columns, *expected,
                "every raster row must sit on the same columns"
            ),
            None => raster_columns = Some(columns),
        }
    }

    // ── The addressing contract of the pilot matrix ────────────────────
    // The pilot suite drives these names through the real input pipeline, but
    // it is a desktop gate; the names it needs are asserted here so a rename
    // fails in the fast gate.
    const STEPPER_LABELS: [&str; 17] = [
        "Tooltip width:",
        "Tooltip max height:",
        "Brightness Threshold (Min):",
        "Brightness Threshold (Max):",
        "Affix Area Height Offset (Top):",
        "Affix Area Height Offset (Bottom):",
        "Affix/Aspect Area Width Offset:",
        "Aspect Area Height Offset (Top):",
        "Type Area Offset (Left):",
        "Minimal OCR Match (Type):",
        "Similarity Threshold (Tooltip):",
        "Similarity Threshold (Affix location):",
        "Similarity Threshold (Aspect location):",
        "Similarity Threshold (Socket location):",
        "Similarity Threshold (Splitter location):",
        "Type Area Offset (Right):",
        "Aspect Area Max Height:",
    ];
    for label in STEPPER_LABELS {
        assert!(
            has_label(app, label),
            "the {label:?} stepper must keep its accessible name"
        );
        for action in [" increment", " decrement"] {
            let action = format!("{label}{action}");
            assert!(
                has_label(app, &action),
                "the {action:?} stepper action must keep its accessible name"
            );
        }
    }
    for label in [
        "Top Most",
        "Take screenshot",
        "Export debug images",
        "Reload preset images",
        "Start",
        "Stop",
        "Open debug output folder",
        "Previous panel",
        "Next panel",
    ] {
        assert!(
            has_label(app, label),
            "the {label:?} control must keep its accessible name"
        );
    }
    // The pager's caption is the upstream banner text (`rsCapItemTypePowerOcrResults`,
    // `DebugView.xaml:387`); the showcase sits on panel 10 so this pins it in
    // the fast gate.
    assert!(
        has_label(app, "OCR Results (ItemType + Power)"),
        "panel 10's caption must match the upstream banner text"
    );
    for label in ["Start", "Stop"] {
        assert!(
            ElementHandle::find_by_accessible_label(app, label)
                .any(|element| element.accessible_role() == Some(AccessibleRole::Button)),
            "the {label:?} control must keep the button role the role-aware pilot click uses"
        );
    }
    assert!(
        ElementHandle::find_by_accessible_label(app, "Type Area Offset (Left):")
            .any(|element| element.accessible_role() == Some(AccessibleRole::Spinbox)),
        "the type-area row must keep the spinbox role the harness scenario drives"
    );
}

/// Whether any element carries `label` as its accessible name.
fn has_label(app: &impl ElementRoot, label: &str) -> bool {
    ElementHandle::find_by_accessible_label(app, label).count() > 0
}
