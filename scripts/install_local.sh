#!/usr/bin/env bash
set -euo pipefail

# Build the desktop app and debug CLI the same way packaging/arch/PKGBUILD does
# and install them into the user's ~/.local prefix. The desktop entry the user
# maintains (~/.local/share/applications/d4lc.desktop) already points at
# ~/.local/bin/d4lc with Icon=d4lc, so this script leaves .desktop files alone
# and only refreshes the launchers, the payload and the hicolor icon.
#
# The app reads the vendored game data (assets/original: localized catalogs,
# system presets) from its working directory, so the payload and the assets
# live together under ~/.local/share/d4lc and the ~/.local/bin launchers start
# the app from there, like the bundle wrappers of package_linux_release.sh. The
# debug CLI launcher passes that directory as D4LC_ASSET_ROOT instead and keeps
# the caller's working directory for the CLI's input and output paths.
# Without the assets the runtime reports "catalog data missing" instead of
# reading anything.
#
# Options:
#   --skip-build   Install the binaries already built under the target dir
#                  (D4LC_INSTALL_TARGET_DIR, then CARGO_TARGET_DIR, default: target) without running cargo.

cd "$(dirname "$0")/.."

SKIP_BUILD=0
for argument in "$@"; do
    case "$argument" in
        --skip-build) SKIP_BUILD=1 ;;
        -h | --help)
            echo "usage: install_local.sh [--skip-build]"
            echo "  --skip-build  install the binaries already built under the target dir"
            exit 0
            ;;
        *)
            echo "install_local.sh: unknown argument: $argument" >&2
            exit 2
            ;;
    esac
done

BIN_DIR="$HOME/.local/bin"
APP_DIR="$HOME/.local/share/d4lc"
ICON_PATH="$HOME/.local/share/icons/hicolor/256x256/apps/d4lc.png"
RELEASE_DIR="${D4LC_INSTALL_TARGET_DIR:-${CARGO_TARGET_DIR:-target}}/release"

if [ "$SKIP_BUILD" -eq 0 ]; then
    ./scripts/check_disk_space.sh
    cargo build --release --locked -p d4lc-app --features "real-runtime leptess-backend wayland-portal"
    cargo build --release --locked -p d4lc-cli --features leptess-backend
fi

for required in "$RELEASE_DIR/d4lc-app" "$RELEASE_DIR/d4lc" assets/original assets/d4lc; do
    [ -e "$required" ] || {
        echo "install_local.sh: required path missing: $required" >&2
        exit 1
    }
done

# Everything is staged next to its destination and moved into place, so a
# failed copy never leaves an install without assets, and a running payload or
# launcher is replaced by a rename instead of being written in place (writing
# over a running binary fails with ETXTBSY).
mkdir -p "$HOME/.local/share"
stage=$(mktemp -d "$HOME/.local/share/.d4lc-install.XXXXXX")
trap 'rm -rf "$stage"' EXIT

# A launcher in ~/.local/bin that runs $3 (how the payload finds the asset
# directory) and starts the payload.
write_launcher() {
    local launcher_path=$1
    local payload_name=$2
    local root_setup=$3
    local staged="$stage/launcher-$payload_name"
    install -d "$(dirname "$launcher_path")"
    cat >"$staged" <<EOF
#!/usr/bin/env bash
# Generated by scripts/install_local.sh
$root_setup
exec "$APP_DIR/bin/$payload_name" "\$@"
EOF
    chmod 0755 "$staged"
    mv -f "$staged" "$launcher_path"
}

# Stage the asset trees and the payloads; nothing below touches the install
# until every copy has succeeded.
mkdir -p "$stage/assets"
cp -a assets/original "$stage/assets/original"
cp -a assets/d4lc "$stage/assets/d4lc"
install -m 0755 "$RELEASE_DIR/d4lc-app" "$stage/d4lc-real"
install -m 0755 "$RELEASE_DIR/d4lc" "$stage/d4lc-debug-real"

install -d "$APP_DIR/bin"
mv -f "$stage/d4lc-real" "$APP_DIR/bin/d4lc-real"
mv -f "$stage/d4lc-debug-real" "$APP_DIR/bin/d4lc-debug-real"

# Replace the asset trees wholesale so files removed upstream do not linger.
# A directory cannot be renamed over a non-empty one: move the old tree aside,
# put the new one in place, and put the old one back if that fails.
if [ -e "$APP_DIR/assets" ]; then
    mv "$APP_DIR/assets" "$stage/assets-old"
fi
if ! mv "$stage/assets" "$APP_DIR/assets"; then
    [ ! -e "$stage/assets-old" ] || mv "$stage/assets-old" "$APP_DIR/assets"
    echo "install_local.sh: could not move the new assets into place" >&2
    exit 1
fi

write_launcher "$BIN_DIR/d4lc" d4lc-real "cd \"$APP_DIR\""
write_launcher "$BIN_DIR/d4lc-debug" d4lc-debug-real "export D4LC_ASSET_ROOT=\"$APP_DIR\""
install -D -m 0644 crates/d4lc-app/assets/d4lc.png "$ICON_PATH"

if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$HOME/.local/share/applications" || true
fi
if command -v gtk-update-icon-cache >/dev/null 2>&1; then
    gtk-update-icon-cache -q -t -f "$HOME/.local/share/icons/hicolor" || true
fi

echo "Installed:"
echo "  $BIN_DIR/d4lc        (desktop app launcher)"
echo "  $BIN_DIR/d4lc-debug  (debug CLI launcher)"
echo "  $APP_DIR             (payload and game data)"
echo "  $ICON_PATH"
